"""SyncAssist: synchronize one Trello list with Markdown planning files.

The module keeps its pure parsing and reconciliation helpers import-safe so
they can be tested without credentials or network access.
"""

# ---------------------------------------------------------------------------
# QUICK README FOR AGENTS
#
# Objective
#   Synchronize a Trello list with Markdown files in PLAN/.
#   A card is linked by the full ID stored in the file's technical JSON block;
#   never use the filename as identity.
#
# Initial setup
#   1. Run: python sync.py --setup
#   2. Enter the API Key obtained at https://trello.com/apps/admin, in the
#      Power-Up's Trello Auth tab.
#   3. Open the User Token authorization link shown by the wizard and paste the
#      token when prompted.
#   4. Enter the board URL and choose an active list.
#   The wizard writes .env with TRELLO_API_KEY, TRELLO_TOKEN and TRELLO_LIST_ID
#   and runs a synchronization when it finishes. Keep the token private.
#
# Normal use
#   Run: python sync.py
#   The project root is the folder containing this script. PLAN/ is created
#   automatically, and each accessible card in the configured list receives a
#   Markdown file.
#   To import immediate PLAN/*.txt files as new todo cards and then sync, run:
#   python sync.py --import
#   Successful source files move to PLAN/.imported/ after their cards are
#   confirmed locally. Invalid sources remain in PLAN/ for review.
#
# How to read and edit cards
#   The top of the file shows the title, description, status, due date, link and
#   comments. The title (first '#'), description, checklists and common label
#   IDs are editable. Comments, due date and the technical block are reference/
#   synchronization data; do not remove existing IDs or markers.
#   Status is controlled by the prefix: todo-name.md leaves dueComplete false;
#   done-name.md sets dueComplete true and creates a due date if necessary.
#   Labels do not determine completion; TRELLO_DONE_LABEL_ID does not exist.
#
# How to create a new card
#   1. Copy PLAN/_modelo-card.md to PLAN/todo-name.md or PLAN/done-name.md.
#   2. Edit the first title and the Description section; keep the technical
#      block.
#   3. Run python sync.py.
#   Only a valid template copy or a template generated by --import creates a
#   card in the configured list.
#   After confirmation, it becomes a card file with the remote ID. The original
#   template is reserved, never creates a card and is kept on every run.
#
# Security and change boundaries
#   Do not commit .env or expose tokens. SyncAssist does not move, delete or
#   archive cards; it does not edit comments or read-only data. For conflicts,
#   review PLAN/.conflicts/ before choosing a resolution.
# ---------------------------------------------------------------------------

